-- Vehicle Service & Maintenance Management System
-- Oracle SQL*Plus schema and demo data
-- Compatible with Oracle Database 12c or later.

CREATE TABLE CUSTOMER (
    Customer_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Customer_Name VARCHAR2(100) NOT NULL,
    Phone VARCHAR2(20) NOT NULL,
    Email VARCHAR2(255) UNIQUE,
    Address VARCHAR2(250)
);

CREATE TABLE VEHICLE_MODEL (
    Model_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Brand VARCHAR2(100) NOT NULL,
    Model_Name VARCHAR2(100) NOT NULL,
    Fuel_Type VARCHAR2(20) DEFAULT 'Petrol' NOT NULL
        CHECK (Fuel_Type IN ('Petrol','Diesel','Electric','Hybrid','CNG')),
    Vehicle_Type VARCHAR2(20) DEFAULT 'Car' NOT NULL
        CHECK (Vehicle_Type IN ('Car','Bike','SUV','Truck','Van','Hatchback','Sedan','MUV')),
    CONSTRAINT UQ_VEHICLE_MODEL_BRAND_NAME UNIQUE (Brand, Model_Name)
);

CREATE TABLE VEHICLE (
    Vehicle_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Registration_No VARCHAR2(30) NOT NULL UNIQUE,
    Customer_ID NUMBER NOT NULL,
    Model_ID NUMBER NOT NULL,
    Manufacture_Year NUMBER(4) CHECK (Manufacture_Year >= 2000),
    Color VARCHAR2(50),
    Mileage NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Mileage >= 0),
    CONSTRAINT FK_VEHICLE_CUSTOMER FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID),
    CONSTRAINT FK_VEHICLE_MODEL FOREIGN KEY (Model_ID) REFERENCES VEHICLE_MODEL(Model_ID)
);

CREATE TABLE MECHANIC (
    Mechanic_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Mechanic_Name VARCHAR2(100) NOT NULL,
    Phone VARCHAR2(20) NOT NULL UNIQUE,
    Specialization VARCHAR2(100),
    Experience_Years NUMBER(3) CHECK (Experience_Years >= 0)
);

CREATE TABLE SERVICE_TYPE (
    Service_Type_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Service_Name VARCHAR2(100) NOT NULL UNIQUE,
    Description VARCHAR2(500),
    Price NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Price >= 0)
);

CREATE TABLE APPOINTMENT (
    Appointment_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Vehicle_ID NUMBER NOT NULL,
    Mechanic_ID NUMBER NOT NULL,
    Service_Type_ID NUMBER NOT NULL,
    Appointment_Date DATE NOT NULL,
    Status VARCHAR2(20) DEFAULT 'Booked' NOT NULL
        CHECK (Status IN ('Booked','In Progress','Completed','Cancelled')),
    Notes VARCHAR2(500),
    CONSTRAINT FK_APPOINTMENT_VEHICLE FOREIGN KEY (Vehicle_ID) REFERENCES VEHICLE(Vehicle_ID),
    CONSTRAINT FK_APPOINTMENT_MECHANIC FOREIGN KEY (Mechanic_ID) REFERENCES MECHANIC(Mechanic_ID),
    CONSTRAINT FK_APPOINTMENT_SERVICE_TYPE FOREIGN KEY (Service_Type_ID) REFERENCES SERVICE_TYPE(Service_Type_ID)
);

CREATE TABLE SERVICE_RECORD (
    Service_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Appointment_ID NUMBER NOT NULL UNIQUE,
    Service_Date DATE NOT NULL,
    Completion_Date DATE,
    Cost NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Cost >= 0),
    Description VARCHAR2(500),
    CONSTRAINT FK_SERVICE_RECORD_APPOINTMENT FOREIGN KEY (Appointment_ID) REFERENCES APPOINTMENT(Appointment_ID)
);

CREATE TABLE SUPPLIER (
    Supplier_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Supplier_Name VARCHAR2(150) NOT NULL,
    Phone VARCHAR2(20),
    Email VARCHAR2(255) UNIQUE,
    Address VARCHAR2(250)
);

CREATE TABLE PART (
    Part_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Part_Name VARCHAR2(150) NOT NULL,
    Category VARCHAR2(100),
    Supplier_ID NUMBER NOT NULL,
    Unit_Price NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Unit_Price >= 0),
    CONSTRAINT FK_PART_SUPPLIER FOREIGN KEY (Supplier_ID) REFERENCES SUPPLIER(Supplier_ID)
);

CREATE TABLE SERVICE_PART (
    Service_ID NUMBER NOT NULL,
    Part_ID NUMBER NOT NULL,
    Quantity NUMBER(8) DEFAULT 1 NOT NULL CHECK (Quantity > 0),
    Unit_Cost NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Unit_Cost >= 0),
    CONSTRAINT PK_SERVICE_PART PRIMARY KEY (Service_ID, Part_ID),
    CONSTRAINT FK_SERVICE_PART_SERVICE FOREIGN KEY (Service_ID) REFERENCES SERVICE_RECORD(Service_ID),
    CONSTRAINT FK_SERVICE_PART_PART FOREIGN KEY (Part_ID) REFERENCES PART(Part_ID)
);

CREATE TABLE INVENTORY (
    Inventory_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Part_ID NUMBER NOT NULL UNIQUE,
    Quantity_In_Stock NUMBER(8) DEFAULT 0 NOT NULL CHECK (Quantity_In_Stock >= 0),
    Reorder_Level NUMBER(8) DEFAULT 0 NOT NULL CHECK (Reorder_Level >= 0),
    Last_Updated DATE DEFAULT SYSDATE,
    CONSTRAINT FK_INVENTORY_PART FOREIGN KEY (Part_ID) REFERENCES PART(Part_ID)
);

CREATE TABLE INVOICE (
    Invoice_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Service_ID NUMBER NOT NULL UNIQUE,
    Invoice_Date DATE DEFAULT SYSDATE NOT NULL,
    Tax_Amount NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Tax_Amount >= 0),
    Total_Amount NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (Total_Amount >= 0),
    Payment_Status VARCHAR2(20) DEFAULT 'Pending' NOT NULL
        CHECK (Payment_Status IN ('Pending','Paid','Partially Paid')),
    CONSTRAINT FK_INVOICE_SERVICE FOREIGN KEY (Service_ID) REFERENCES SERVICE_RECORD(Service_ID)
);

CREATE TABLE PAYMENT (
    Payment_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Invoice_ID NUMBER NOT NULL,
    Payment_Date DATE DEFAULT SYSDATE NOT NULL,
    Amount NUMBER(10,2) NOT NULL CHECK (Amount >= 0),
    Payment_Mode VARCHAR2(30) NOT NULL
        CHECK (Payment_Mode IN ('Cash','Card','UPI','Bank Transfer','Net Banking')),
    CONSTRAINT FK_PAYMENT_INVOICE FOREIGN KEY (Invoice_ID) REFERENCES INVOICE(Invoice_ID)
);

CREATE TABLE WARRANTY (
    Warranty_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Service_ID NUMBER,
    Part_ID NUMBER,
    Start_Date DATE NOT NULL,
    End_Date DATE NOT NULL,
    Details VARCHAR2(500),
    CONSTRAINT CK_WARRANTY_DATES CHECK (End_Date >= Start_Date),
    CONSTRAINT FK_WARRANTY_SERVICE FOREIGN KEY (Service_ID) REFERENCES SERVICE_RECORD(Service_ID),
    CONSTRAINT FK_WARRANTY_PART FOREIGN KEY (Part_ID) REFERENCES PART(Part_ID)
);

CREATE TABLE FEEDBACK (
    Feedback_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Service_ID NUMBER NOT NULL,
    Customer_ID NUMBER NOT NULL,
    Rating NUMBER(1) NOT NULL CHECK (Rating BETWEEN 1 AND 5),
    Comments VARCHAR2(1000),
    Feedback_Date DATE DEFAULT SYSDATE,
    CONSTRAINT FK_FEEDBACK_SERVICE FOREIGN KEY (Service_ID) REFERENCES SERVICE_RECORD(Service_ID),
    CONSTRAINT FK_FEEDBACK_CUSTOMER FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID)
);

CREATE OR REPLACE VIEW CustomerVehicleAppointment AS
SELECT c.Customer_ID, c.Customer_Name, c.Phone, c.Email,
       v.Vehicle_ID, v.Registration_No, vm.Brand, vm.Model_Name,
       a.Appointment_ID, a.Appointment_Date, a.Status
FROM CUSTOMER c
JOIN VEHICLE v ON c.Customer_ID = v.Customer_ID
JOIN VEHICLE_MODEL vm ON v.Model_ID = vm.Model_ID
LEFT JOIN APPOINTMENT a ON v.Vehicle_ID = a.Vehicle_ID;

